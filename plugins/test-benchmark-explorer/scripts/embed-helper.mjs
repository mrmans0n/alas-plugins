import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const parts = ["common", "importers", "query", "source", "observer", "store", "capture", "bridge"];
const source = parts.filter(name => existsSync(join(root, "helper", `${name}.py`)))
  .map(name => readFileSync(join(root, "helper", `${name}.py`), "utf8")).join("\n\n");
if (Buffer.byteLength(source) > 180 * 1024) throw new Error("Embedded helper exceeds stdin budget");
mkdirSync(join(root, "dist"), { recursive: true });
mkdirSync(join(root, "src"), { recursive: true });
writeFileSync(join(root, "dist/capture.py"), source);
writeFileSync(join(root, "src/helper-source.ts"), `// Generated by scripts/embed-helper.mjs.\nexport const HELPER = ${JSON.stringify(source)};\n`);
